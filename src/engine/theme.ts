/**
 * Visual themes. Sprites are swapped wholesale (see `modernSkin.ts` and
 * `blockySkin.ts`); the palette covers everything the scenes draw directly
 * (text, lines, overlays, cards, buttons, brick shadows and extrusions).
 */
import { CLASSIC_FX, fxProfile, type FxProfile } from "./fxProfile";
import type { Color } from "../core/color";

export type ThemeName =
  "classic" | "pigment" | "delicious" | "crystals" | "halloween" | "winter" | "christmas" | "gooey" | "vintage" | "nature" | "blocky" | "spectra";

/** Order the theme toggle cycles through. */
export const THEME_ORDER: readonly ThemeName[] = [
  "pigment",
  "delicious",
  "crystals",
  "halloween",
  "winter",
  "christmas",
  "gooey",
  "vintage",
  "nature",
  "spectra",
  "blocky",
  "classic",
];

export function nextTheme(current: ThemeName): ThemeName {
  const i = THEME_ORDER.indexOf(current);
  return THEME_ORDER[(i + 1) % THEME_ORDER.length];
}

