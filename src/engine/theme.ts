export interface UiPalette {
  /** Overlay card fill, edge and hard shadow / extrusion. */
  card: string;
  cardEdge: string;
  cardShadow: string;
  /** Full-screen dim behind cards. */
  dim: string;
  primary: string;
  primaryHover: string;
  primaryText: string;
  secondary: string;
  secondaryHover: string;
  secondaryEdge: string;
  secondaryText: string;
}

export interface Palette {
  name: ThemeName;
  /** Classic uses the original art and layout; generated themes share the modern layout. */
  kind: "classic" | "generated";
  /** How the board backdrop is painted. */
  backdrop:
    | "sprites"
    | "paper"
    | "delicious"
    | "crystals"
    | "halloween"
    | "winter"
    | "christmas"
    | "gooey"
    | "vintage"
    | "nature"
    | "blocky"
    | "spectra"
    | "stainedglass"
    | "lantern"
    | "origami"
    | "circuit"
    | "knit"
    | "neon"
    | "seaglass"
    | "pixel";
  /** How bricks are drawn around their face sprite. */
  brickStyle: "flat" | "chip" | "extruded" | "gel";
  /** Fill timer: a bar under the grid, or the next tray well filling with the incoming colour. */
  timer: "bar" | "wells";
  /** What flies out of a popped brick. */
  popStyle:
    | "flecks"
    | "dots"
    | "cubes"
    | "splat"
    | "sprinkles"
    | "shards"
    | "bats"
    | "snow"
    | "confetti"
    | "leaves"
    | "scraps"
    | "embers"
    | "bubbles"
    | "yarn"
    | "pixels";
  /** Title-screen decoration: scattered tiles, tiles floating up, or the flipping brick wall. */
  titleDeco: "chips" | "bubbles" | "wall";
  /** Veil over the decoration while a sub-menu is open. */
  titleDim: string;
  /** Canvas clear colour behind everything (also the page background). */
  background: string;
  hudText: string;
  hudMuted: string;
  gridLine: string;
  gridAlpha: number;
  /** Replenish-selector crosshair. */
  crosshair: string;
  titleText: string;
  titleMuted: string;
  /** Accent for the title's furthest-world stat when the button colour would vanish on the bottom band. */
  titleAccent?: string;
  overlayText: string;
  overlayAccent: string;
  tutorialText: string;
  tutorialShadow: string;
  /** Font stack for HUD and body text drawn by the scenes. */
  font: string;
  /** Font stack for display text (titles, big numbers). */
  display: string;
  ui: UiPalette;
  /** Hard offset shadow under every chip (chip style), or null. */
  brickShadow: string | null;
  /** Side-face colour per brick colour (extruded style), or null. */
  brickSide: Record<Color, string> | null;
  /** Faint rounded square drawn in each empty board cell, or null. */
  emptyCell: string | null;
  /** Shelf strip under the replenish line, or null. */
  ledge: string | null;
  /** Flash over the board on a multiplier pop. */
  flash: string;
  flashAlpha: number;
  /** Score / callout text colour and its shadow. */
  callout: string;
  calloutShadow: string;
  /** Chain multiplier colours, indexed by multiplier. */
  multColors: string[];
  /** Flat brick colours by colour bits, for particles and other effects. */
  brickColors: Record<Color, string>;
  /** Hold-slot well colours. */
  well: string;
  wellEdge: string;
  wellActive: string;
  wellActiveEdge: string;
  /** Faint "H" in the empty hold slot. */
  wellHint: string;
  /** Pill behind the level label. */
  pill: string;
  pillEdge: string;
  /** Chain meter track and progress bar track / max fill. */
  track: string;
  trackMax: string;
  /** Flash colour over the progress bar on a push. */
  barFlash: string;
  /** Subtract-goal accent. */
  goalAccent: string;
  /** Bar flash + ring colour for combine. */
  ring: string;
  dust: [string, string];
  /** Glow treatment on score, chain meter and rings. */
  glow: boolean;
  /** Pop flash takes the popped colour instead of `flash`. */
  flashFromBrick: boolean;
  /** Particles blend additively. */
  particlesAdditive: boolean;
  /** Pops leave a fading paint stain on the board. */
  stains: boolean;
  /** The stain's colour; null stains in the popped brick's colour. */
  stainColor: string | null;
  /** Draw sprites with smoothing off (chunky pixels) and snap debris to a grid. */
  pixelated: boolean;
  /** Settled same-colour neighbours fuse: the seam between them is painted over so a group reads as one piece. */
  fuse: boolean;
  /** Which treatments the shared effects layer applies for this theme. */
  fx: FxProfile;
  /** The material every game sound is synthesised on; null keeps the original recordings (Classic). */
  sound: SoundProfile | null;
}

